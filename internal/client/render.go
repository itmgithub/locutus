package client

import (
	"fmt"
	"strings"
)

// Fixed paths in the container.
const (
	WrapperPath        = "/usr/local/bin/locutus-borg-wrapper"
	BinaryPath         = "/usr/local/bin/locutus-client"
	SettingsPath       = "/etc/locutus-client.json" // the settings of the running container, for "apply"
	StateFile          = "locutus.json"             // in the configuration directory: the pushed configuration
	AuthorizedKeysDir  = "/etc/ssh/authorized_keys" // root owned: the user borg cannot change its keys
	sshdConfigPath     = "/etc/ssh/sshd_config"
	sshConfigPath      = "/etc/ssh/ssh_config"
	knownHostsPath     = "/etc/ssh/ssh_known_hosts"
	sudoersPath        = "/etc/sudoers.d/locutus"
	hostKeyName        = "ssh_host_ed25519_key"
	secureSudoPath     = "/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"
	generatedByComment = "# Generated by locutus-client from the configuration that Locutus pushes; do not change.\n"
)

// AuthorizedKeys returns the authorized_keys of the user borg: every key is
// restricted to exactly what Locutus does with it.
func (c *Config) AuthorizedKeys(cmd Commands) string {
	var b strings.Builder
	b.WriteString(generatedByComment)
	from := ""
	if c.ManagerFrom != "" {
		from = fmt.Sprintf("from=\"%s\",", c.ManagerFrom)
	}
	b.WriteString("\n# Locutus: pushes the configuration of this container\n")
	fmt.Fprintf(&b, "%scommand=\"%s -n %s apply\",restrict %s\n", from, cmd.Sudo, BinaryPath, c.ManagerKey)
	for _, r := range c.Repositories {
		appendOnly := ""
		if r.AppendOnly {
			appendOnly = " --append-only"
		}
		fmt.Fprintf(&b, "\n# Repository %s: normal key\n", r.Name)
		fmt.Fprintf(&b, "command=\"borg serve%s --restrict-to-repository %s\",restrict %s\n", appendOnly, r.Path, r.Key)
		if r.PruneKey != "" {
			fmt.Fprintf(&b, "# Repository %s: prune key, only from Locutus\n", r.Name)
			fmt.Fprintf(&b, "from=\"%s\",command=\"borg serve --restrict-to-repository %s\",restrict %s\n", r.PruneFrom, r.Path, r.PruneKey)
		}
	}
	if c.Client != nil {
		opt := ""
		if !c.Client.Restore {
			opt = " --no-restore"
		}
		b.WriteString("\n# Client: backups and restores of the volumes, through the wrapper\n")
		fmt.Fprintf(&b, "command=\"%s%s\",restrict,agent-forwarding %s\n", WrapperPath, opt, c.Client.Key)
	}
	return b.String()
}

// SSHDConfig returns the configuration of the SSH server: only the user
// borg, only public keys, no shell, no forwarding except the agent that
// the client role needs. Agent forwarding is allowed here, but every key
// in authorized_keys is "restrict"ed, and only the client key gets it back,
// so the file does not depend on the pushed configuration.
func (c *Config) SSHDConfig() string {
	return generatedByComment + `Port ` + fmt.Sprint(defaultSSHPort) + `
HostKey ` + c.ConfigDir + `/ssh/` + hostKeyName + `
AuthorizedKeysFile ` + AuthorizedKeysDir + `/%u
AllowUsers ` + sshUser + `
PermitRootLogin no
PubkeyAuthentication yes
PasswordAuthentication no
KbdInteractiveAuthentication no
PermitEmptyPasswords no
PermitUserEnvironment no
PermitTTY no
AllowAgentForwarding yes
AllowTcpForwarding no
AllowStreamLocalForwarding no
GatewayPorts no
X11Forwarding no
PermitTunnel no
ClientAliveInterval 30
ClientAliveCountMax 6
MaxAuthTries 3
LoginGraceTime 30
LogLevel INFO
PidFile /run/sshd.pid
`
}

// SSHConfig returns the SSH client configuration with which borg (as root,
// through sudo) connects to the repository servers: only with the key that
// Locutus forwards during a backup, and only to known servers.
func (c *Config) SSHConfig() string {
	return generatedByComment + `Host *
    IdentitiesOnly no
    IdentityAgent SSH_AUTH_SOCK
    ForwardAgent no
    ForwardX11 no
    ClearAllForwardings yes
    BatchMode yes
    StrictHostKeyChecking yes
    GlobalKnownHostsFile ` + knownHostsPath + `
    UserKnownHostsFile /dev/null
    UpdateHostKeys no
    ServerAliveInterval 30
    ServerAliveCountMax 6
`
}

// Commands are the full paths of the commands the sudo rules allow.
type Commands struct {
	Sudo, Borg, Stat, Tar string
}

// Sudoers returns the sudo rules: Locutus may apply a pushed configuration
// and, for the client role, the rules of the README for a client with sudo.
func (c *Config) Sudoers(cmd Commands) string {
	var b strings.Builder
	b.WriteString(generatedByComment)
	fmt.Fprintf(&b, "Defaults secure_path=\"%s\"\n\n", secureSudoPath)
	b.WriteString("# The management key of Locutus: apply a pushed configuration. SSH_CLIENT\n# tells where Locutus connects from.\n")
	fmt.Fprintf(&b, "Defaults!%s env_keep += \"SSH_CLIENT\"\n", BinaryPath)
	fmt.Fprintf(&b, "%s ALL=(root) NOPASSWD: %s apply\n", sshUser, BinaryPath)
	if c.Client == nil {
		return b.String()
	}
	b.WriteString("\n")
	b.WriteString("# Backups: borg as root. The variables carry the passphrase and the\n# repository key through sudo.\n")
	fmt.Fprintf(&b, "Defaults!%s env_keep += \"BORG_PASSPHRASE_FD BORG_UNKNOWN_UNENCRYPTED_REPO_ACCESS_IS_OK BORG_RELOCATED_REPO_ACCESS_IS_OK SSH_AUTH_SOCK\"\n", cmd.Borg)
	fmt.Fprintf(&b, "%s ALL=(root) NOPASSWD: %s\n", sshUser, cmd.Borg)
	if c.Client.Restore {
		b.WriteString("\n# Restores\n")
		fmt.Fprintf(&b, "%s ALL=(root) NOPASSWD: %s, %s -x -p -f - -C /\n", sshUser, cmd.Stat, cmd.Tar)
	}
	return b.String()
}
