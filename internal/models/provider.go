package models

import (
	"encoding/json"
)

// Identity provider types.
const (
	ProviderOIDC = "oidc"
	ProviderSAML = "saml"
)

// OIDCConfig holds the settings of an OpenID Connect provider.
type OIDCConfig struct {
	IssuerURL     string `json:"issuer_url"`
	ClientID      string `json:"client_id"`
	ClientSecret  string `json:"client_secret"`
	Scopes        string `json:"scopes"`         // space separated, "openid" is always added
	UsernameClaim string `json:"username_claim"` // defaults to preferred_username
}

// SAMLConfig holds the settings of a SAMLv2 identity provider. The service
// provider key pair is generated by Locutus when the provider is created.
type SAMLConfig struct {
	IDPMetadataURL    string `json:"idp_metadata_url"`
	IDPMetadataXML    string `json:"idp_metadata_xml"`
	EntityID          string `json:"entity_id"` // optional, defaults to the metadata URL
	UsernameAttribute string `json:"username_attribute"`
	SPCertificatePEM  string `json:"sp_certificate_pem"`
	SPKeyPEM          string `json:"sp_key_pem"`
}

// IdentityProvider is an external OIDC or SAMLv2 login source.
type IdentityProvider struct {
	ID      int64
	Type    string
	Name    string
	Enabled bool
	OIDC    OIDCConfig
	SAML    SAMLConfig
}

// configJSON returns the encrypted provider configuration; it holds the
// OIDC client secret or the SAML service provider key.
func (s *Store) configJSON(p *IdentityProvider) (string, error) {
	var v any = p.OIDC
	if p.Type == ProviderSAML {
		v = p.SAML
	}
	b, err := json.Marshal(v)
	if err != nil {
		return "", err
	}
	return s.box.Encrypt(string(b))
}

func (s *Store) scanProvider(row interface{ Scan(...any) error }) (*IdentityProvider, error) {
	var p IdentityProvider
	var cfg string
	if err := row.Scan(&p.ID, &p.Type, &p.Name, &p.Enabled, &cfg); err != nil {
		return nil, notFound(err)
	}
	plain, err := s.box.Decrypt(cfg)
	if err != nil {
		return nil, err
	}
	var target any = &p.OIDC
	if p.Type == ProviderSAML {
		target = &p.SAML
	}
	if plain != "" {
		if err := json.Unmarshal([]byte(plain), target); err != nil {
			return nil, err
		}
	}
	return &p, nil
}

// ListProviders returns all identity providers; with onlyEnabled only the active ones.
func (s *Store) ListProviders(onlyEnabled bool) ([]*IdentityProvider, error) {
	q := `SELECT id, type, name, enabled, config FROM identity_providers`
	if onlyEnabled {
		q += ` WHERE enabled = 1`
	}
	rows, err := s.db.Query(q + ` ORDER BY name COLLATE NOCASE`)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var list []*IdentityProvider
	for rows.Next() {
		p, err := s.scanProvider(rows)
		if err != nil {
			return nil, err
		}
		list = append(list, p)
	}
	return list, rows.Err()
}

// GetProvider returns one identity provider.
func (s *Store) GetProvider(id int64) (*IdentityProvider, error) {
	return s.scanProvider(s.db.QueryRow(`SELECT id, type, name, enabled, config FROM identity_providers WHERE id = ?`, id))
}

// SaveProvider inserts (ID == 0) or updates an identity provider.
func (s *Store) SaveProvider(p *IdentityProvider) error {
	cfg, err := s.configJSON(p)
	if err != nil {
		return err
	}
	if p.ID == 0 {
		res, err := s.db.Exec(`INSERT INTO identity_providers (type, name, enabled, config, created_at) VALUES (?, ?, ?, ?, ?)`,
			p.Type, p.Name, p.Enabled, cfg, now())
		if err != nil {
			return err
		}
		p.ID, err = res.LastInsertId()
		return err
	}
	_, err = s.db.Exec(`UPDATE identity_providers SET name = ?, enabled = ?, config = ? WHERE id = ?`, p.Name, p.Enabled, cfg, p.ID)
	return err
}

// DeleteProvider removes an identity provider together with its users.
func (s *Store) DeleteProvider(id int64) error {
	_, err := s.db.Exec(`DELETE FROM identity_providers WHERE id = ?`, id)
	return err
}
